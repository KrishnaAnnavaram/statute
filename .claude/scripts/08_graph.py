def cypher_value(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


KEY_PROPERTY = {
    "File": "file_id", "Object": "object_id", "Parameter": "parameter_id",
    "Statement": "statement_id", "Table": "table", "Column": "column_id",
    "Index": "index", "Sequence": "sequence", "BusinessRule": "rule_id",
    "RuleSet": "rule_set_id", "State": "state_id", "Gap": "gap_id",
    "BlindSpot": "blind_spot",
}


def write_export(graph, run_dir: Path) -> dict:
    nodes_dir, rels_dir = run_dir / "nodes", run_dir / "rels"
    nodes_dir.mkdir(parents=True, exist_ok=True)
    rels_dir.mkdir(parents=True, exist_ok=True)

    lines = ["// Generated by Stage 8. MERGE throughout, so re-running is safe.",
             "// Load order matters: nodes first, then relationships.", ""]

    # Uniqueness constraints double as the indexes the MERGEs need.
    for label, keyprop in KEY_PROPERTY.items():
        if graph.nodes.get(label):
            lines.append(f"CREATE CONSTRAINT {label.lower()}_key IF NOT EXISTS "
                         f"FOR (n:{label}) REQUIRE n.{keyprop} IS UNIQUE;")
    lines.append("")

    for label, bucket in sorted(graph.nodes.items()):
        if not bucket:
            continue
        keyprop = KEY_PROPERTY.get(label, "id")
        prop_names = sorted({k for props in bucket.values() for k in props})
        with (nodes_dir / f"{label}.csv").open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow([keyprop] + prop_names)
            for key, props in sorted(bucket.items()):
                w.writerow([key] + [props.get(p, "") for p in prop_names])
        lines.append(f"// ---- {label} ({len(bucket)}) ----")
        for key, props in sorted(bucket.items()):
            assigns = ", ".join(f"n.{p} = {cypher_value(props[p])}" for p in prop_names
                                if props.get(p) is not None)
            stmt = f"MERGE (n:{label} {{{keyprop}: {cypher_value(key)}}})"
            lines.append(stmt + (f" SET {assigns};" if assigns else ";"))
        lines.append("")

    by_type = {}
    for rtype, fl, fk, tl, tk, props in graph.rels:
        by_type.setdefault(rtype, []).append((fl, fk, tl, tk, props))
    for rtype, items in sorted(by_type.items()):
        with (rels_dir / f"{rtype}.csv").open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(["from_label", "from_key", "to_label", "to_key", "properties"])
            for fl, fk, tl, tk, props in items:
                w.writerow([fl, fk, tl, tk, json.dumps(props) if props else ""])
        lines.append(f"// ---- {rtype} ({len(items)}) ----")
        for fl, fk, tl, tk, props in items:
            fkp, tkp = KEY_PROPERTY.get(fl, "id"), KEY_PROPERTY.get(tl, "id")
            setter = ""
            if props:
                setter = " SET " + ", ".join(f"r.{k} = {cypher_value(v)}"
                                             for k, v in props.items())
            lines.append(
                f"MATCH (a:{fl} {{{fkp}: {cypher_value(fk)}}}), "
                f"(b:{tl} {{{tkp}: {cypher_value(tk)}}}) "
                f"MERGE (a)-[r:{rtype}]->(b){setter};")
        lines.append("")

    (run_dir / "import.cypher").write_text("\n".join(lines), encoding="utf-8")
    node_counts, rel_counts = graph.counts()
    return {"nodes": node_counts, "relationships": rel_counts}


CONCEPTS = [
    ("Hot column", "A column read or written by more than two program units — change last.",
     """MATCH (o:Object)-[:READS_COLUMN|WRITES_COLUMN]->(c:Column)
WITH c, count(DISTINCT o) AS units WHERE units > 2
SET c:HotColumn SET c.dependent_units = units RETURN c.column_id, units;"""),
    ("Rule-bearing statement", "A statement that implements at least one business rule.",
     """MATCH (br:BusinessRule)-[:IMPLEMENTED_AT]->(s:Statement)
SET s:RuleBearing RETURN s.statement_id, collect(br.rule_id);"""),
    ("Write path", "Statements on a control-flow path that ends in a write.",
     """MATCH p = (s:Statement)-[:FOLLOWS|BRANCHES_TO*1..10]->(w:Statement)
WHERE w.type IN ['UPDATE','INSERT','DELETE','MERGE']
RETURN DISTINCT s.statement_id, w.type, w.line;"""),
]

CONSTRAINTS = [
    ("Every rule traces to source",
     "A rule with no program unit and no table cannot be verified.",
     """MATCH (br:BusinessRule)
WHERE NOT (br)-[:ENFORCED_IN]->() AND NOT (br)-[:CONSTRAINS_TABLE]->()
RETURN br.rule_id;"""),
    ("No orphan columns in rules",
     "A rule constraining a column that does not exist indicates a join error.",
     """MATCH (br:BusinessRule)-[:CONSTRAINS]->(c:Column)
WHERE NOT (:Table)-[:HAS_COLUMN]->(c) RETURN br.rule_id, c.column_id;"""),
    ("Unenforced constraints are visible",
     "Any rule the database does not enforce must be flagged for review.",
     """MATCH (br:BusinessRule) WHERE br.is_enforced = false AND br.needs_review = false
RETURN br.rule_id, br.name;"""),
]


def write_docs(run_dir: Path, stats: dict, upstream: dict) -> None:
    n, r = stats["nodes"], stats["relationships"]
    lines = [
        "# Knowledge Graph — import and query guide", "",
        "Generated deterministically from the pipeline artifacts. No language model "
        "produced any node, relationship or query in this export.", "",
        "## What is in it", "",
        "| Node | Count |", "|---|---|",
        *[f"| `{k}` | {v} |" for k, v in n.items()], "",
        "| Relationship | Count |", "|---|---|",
        *[f"| `{k}` | {v} |" for k, v in r.items()], "",
        "## Loading it", "",
        "**Option A — Neo4j Browser or cypher-shell.** Run `import.cypher` top to "
        "bottom. It uses `MERGE` throughout, so re-running is safe and idempotent.", "",
        "```bash", "cat import.cypher | cypher-shell -u neo4j -p <password>", "```", "",
        "**Option B — CSV.** `nodes/` and `rels/` hold one file per label and "
        "relationship type, for `LOAD CSV` or the admin importer.", "",
        "**Option C — no Neo4j at all.** Ask questions directly against the "
        "artifacts:", "",
        "```bash",
        'python .claude/scripts/08_graph.py --ask "what breaks if I change ACCOUNTS.BALANCE"',
        "python .claude/scripts/08_graph.py --list-questions", "```", "",
        "The local answer and the Neo4j answer come from the same model, so they "
        "cannot disagree.", "",
        "## Questions this graph answers", "",
    ]
    for i in INTENTS:
        lines += [f"### {i.question}", "", "```cypher", i.cypher.strip(), "```", ""]

    lines += ["## Concepts — derived views", "",
              "Run these after loading to enrich the graph. They add labels and "
              "properties rather than new facts, so they are safe to re-run.", ""]
    for name, why, q in CONCEPTS:
        lines += [f"### {name}", "", why, "", "```cypher", q.strip(), "```", ""]

    lines += ["## Constraints — these should return nothing", "",
              "Each query below is a validation. A non-empty result is a defect in the "
              "pipeline or a genuine finding about the codebase.", ""]
    for name, why, q in CONSTRAINTS:
        lines += [f"### {name}", "", why, "", "```cypher", q.strip(), "```", ""]

    lines += ["## What this graph cannot see", "",
              "No automated dependency analysis is complete. These limits are exported "
              "as `BlindSpot` nodes so they are queryable rather than assumed away:", "",
              "```cypher", "MATCH (b:BlindSpot) RETURN b.blind_spot, b.detail;", "```", "",
              "Treat the graph as a strong lower bound on dependencies, never an upper "
              "bound. Human validation remains necessary.", "",
              "## Provenance", "", "| Setting | Value |", "|---|---|",
              *[f"| {k} | `{v}` |" for k, v in upstream.items() if v], ""]
    (run_dir / "README.md").write_text("\n".join(lines), encoding="utf-8")


