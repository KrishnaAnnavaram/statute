#!/usr/bin/env python3
"""
Stage 8: KNOWLEDGE GRAPH (deterministic, no LLM)
================================================

Turns the pipeline's artifacts into a queryable knowledge graph, and provides a
plain-English interface over it that works with or without Neo4j installed.

    python .claude/scripts/08_graph.py
    python .claude/scripts/08_graph.py --ask "what breaks if I change ACCOUNTS.BALANCE"
    python .claude/scripts/08_graph.py --list-questions

WHY THIS AGENT WAS REDESIGNED
-----------------------------
The predecessor exported 5 node types and 7 relationship types from 4 of the 7
upstream artifacts. Measured gaps:

  - no Column node, so column-level impact analysis — the single best reason to
    put this in a graph — was impossible
  - no Statement node, so the exact statement_id provenance the pipeline works
    hard to preserve was flattened to "somewhere in this procedure"
  - Agents 4, 6 and 7 were never opened: no complexity, shape, transaction
    behaviour, states or gaps
  - thin properties: objects carried only type/file_id/parse_status, so nothing
    could be ranked or filtered
  - no query interface at all, and a graph nobody knows how to query is a graph
    nobody uses

DESIGN
------
1.  ONE MODEL, TWO VIEWS. `lib_graph_model` builds an in-memory property graph;
    the CSV/Cypher export and the question interface are both views over it, so
    a locally-answered question and the same question in Neo4j cannot disagree.

2.  COLUMN AND STATEMENT ARE NODES. Property-graph practice says a thing with
    several independent relationships must be a node. A Column is read, written,
    constrained and indexed; a Statement carries control flow and rule
    provenance. Making them properties would make the interesting questions
    unaskable.

3.  A CODE PROPERTY GRAPH LAYER. Yamaguchi et al. (IEEE S&P 2014) showed that
    joining AST, control flow and data dependence into one graph answers
    questions none of them answers alone. We already hold all three.

4.  CONCEPTS AND CONSTRAINTS, after jQAssistant. The export ships derived-view
    Cypher (concepts) and validation Cypher that should return nothing
    (constraints), so an analyst can extend the graph without touching this
    extractor.

5.  DETERMINISTIC ENGLISH. Questions are matched against a named intent
    catalogue, never generated by a model. An unmatched question is reported as
    a miss with a list of what IS supported. Total precision, imperfect recall —
    the correct trade when a wrong impact-analysis answer is worse than none.

6.  DECLARED BLIND SPOTS. The impact-analysis literature is unanimous that no
    automated approach is complete. Dynamic SQL, external callers, unresolved
    calls and trigger side effects are exported as BlindSpot nodes rather than
    left as a silent absence.

This agent remains OPTIONAL: no other stage depends on it, and the JSON
artifacts stay the pipeline's source of truth.

DESIGN REFERENCES
-----------------
  Yamaguchi, Golde, Arp & Rieck (2014)  Code Property Graphs, IEEE S&P
  jQAssistant                            scan -> graph -> concepts + constraints
  Lehnert, A review of software change impact analysis
                                         no automated approach is complete
  CAST Imaging / Thoughtworks CodeConcise
                                         industry precedent for a Neo4j knowledge base
  Neo4j property-graph modelling guidance
                                         node vs relationship vs property
"""

