def render_answer(res: dict) -> str:
    if not res.get("ok"):
        out = [f"Could not answer: {res['reason']}", "", "This interface answers:"]
        out += [f"  - {s}" for s in res.get("suggestions", [])]
        return "\n".join(out)
    out = [f"Question type : {res['question']}", f"Subject       : {res['subject']}",
           f"Results       : {res['row_count']}", ""]
    if res["rows"]:
        widths = [max([len(str(h))] + [len(str(r[i])) for r in res["rows"]])
                  for i, h in enumerate(res["header"])]
        out.append("  " + "  ".join(str(h).ljust(widths[i])
                                    for i, h in enumerate(res["header"])))
        out.append("  " + "  ".join("-" * w for w in widths))
        for row in res["rows"]:
            out.append("  " + "  ".join(str(c).ljust(widths[i]) for i, c in enumerate(row)))
    else:
        out.append("  (nothing found — this is a real answer, not a failure)")
    out += ["", "Equivalent Cypher:", ""]
    out += ["  " + l for l in res["cypher"].strip().splitlines()]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description="Stage 8: knowledge graph export and query")
    ap.add_argument("--inventory-root", default="output/inventory")
    ap.add_argument("--parser-root", default="output/parser")
    ap.add_argument("--data-root", default="output/data")
    ap.add_argument("--logic-root", default="output/logic")
    ap.add_argument("--rules-root", default="output/rules")
    ap.add_argument("--diagram-root", default="output/diagram")
    ap.add_argument("--report-root", default="output/final_report")
    ap.add_argument("--run", default="latest")
    ap.add_argument("--output-root", default="output/graph")
    ap.add_argument("--output", default=None)
    ap.add_argument("--ask", default=None, help="Ask a question in plain English.")
    ap.add_argument("--list-questions", action="store_true")
    ap.add_argument("--json", action="store_true", help="Machine-readable answer.")
    args = ap.parse_args()

    if args.list_questions:
        print("Questions this interface answers:\n")
        for i in INTENTS:
            print(f"  {i.question}")
        print("\nName entities exactly, e.g. ACCOUNTS.BALANCE, SP_TRANSFER_FUNDS, BR-014.")
        return

    graph = build_graph(collect_artifacts(args), humanise, object_title, entity_title)

    if args.ask:
        res = ask(graph, args.ask)
        print(json.dumps(res, indent=2, default=str) if args.json else render_answer(res))
        sys.exit(0 if res.get("ok") else 2)

    versioned = args.output is None
    run_version = generate_run_version()
    run_dir = Path(args.output_root) / run_version if versioned else Path(args.output)
    run_dir.mkdir(parents=True, exist_ok=True)

    stats = write_export(graph, run_dir)
    upstream = {"run_selector": args.run}
    write_docs(run_dir, stats, upstream)

    artifact = {
        "pipeline_stage": "8_graph", "schema_version": "2.0",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "upstream": upstream, "design_references": DESIGN_REFERENCES,
        "stats": stats,
        "supported_questions": [{"intent": i.name, "question": i.question} for i in INTENTS],
        "concepts": [{"name": n, "purpose": w} for n, w, _ in CONCEPTS],
        "constraints": [{"name": n, "purpose": w} for n, w, _ in CONSTRAINTS],
        "blind_spots": [{"kind": k, "detail": p.get("detail")}
                        for k, p in graph.nodes.get("BlindSpot", {}).items()],
    }
    (run_dir / "graph_artifact.json").write_text(
        json.dumps(artifact, indent=2, ensure_ascii=False), encoding="utf-8")

    if versioned:
        (run_dir / "run_meta.json").write_text(json.dumps(
            {"stage": "8_graph", "run_version": run_version, "status": "success",
             "generated_at": artifact["generated_at"], "stats": stats}, indent=2),
            encoding="utf-8")
        (Path(args.output_root) / "latest.json").write_text(json.dumps(
            {"run_version": run_version, "path": f"{run_version}/graph_artifact.json",
             "updated_at": artifact["generated_at"]}, indent=2), encoding="utf-8")

    print("=== Knowledge Graph Complete ===")
    print(f"Nodes         : {sum(stats['nodes'].values())} across {len(stats['nodes'])} labels")
    for k, v in stats["nodes"].items():
        print(f"    {k:<14}{v}")
    print(f"Relationships : {sum(stats['relationships'].values())} across "
          f"{len(stats['relationships'])} types")
    for k, v in stats["relationships"].items():
        print(f"    {k:<20}{v}")
    print(f"Questions     : {len(INTENTS)} supported")
    print(f"Blind spots   : {len(artifact['blind_spots'])} declared")
    print(f"Output        : {run_dir / 'graph_artifact.json'}")
    print("================================")


if __name__ == "__main__":
    main()
