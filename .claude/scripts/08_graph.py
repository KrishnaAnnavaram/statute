def generate_run_version() -> str:
    now = datetime.now(timezone.utc)
    return now.strftime("%Y-%m-%dT%H.%M.%S.") + f"{now.microsecond // 1000:03d}Z"


def load_run(root: str, run: str, filename: str):
    root_path = Path(root)
    if run == "latest":
        rv = json.loads((root_path / "latest.json").read_text(encoding="utf-8"))["run_version"]
    else:
        rv = run
    return json.loads((root_path / rv / filename).read_text(encoding="utf-8")), root_path / rv


def optional(root, run, filename):
    try:
        return load_run(root, run, filename)
    except (FileNotFoundError, KeyError, json.JSONDecodeError):
        return {}, None


def collect_artifacts(args) -> dict:
    inv, _ = optional(args.inventory_root, args.run, "inventory-artifact.json")
    parser, proot = load_run(args.parser_root, args.run, "parser_artifact.json")
    data, _ = optional(args.data_root, args.run, "data_artifact.json")
    logic, lroot = optional(args.logic_root, args.run, "logic_artifact.json")
    rules, _ = optional(args.rules_root, args.run, "rules_artifact.json")
    diagrams, _ = optional(args.diagram_root, args.run, "diagrams_artifact.json")
    brd, _ = optional(args.report_root, args.run, "brd_index.json")

    parser_records = {}
    for oid, rel in (parser.get("object_index") or {}).items():
        p = proot / rel
        if p.exists():
            parser_records[oid] = json.loads(p.read_text(encoding="utf-8"))
    logic_records = {}
    for oid, rel in (logic.get("object_index") or {}).items():
        p = (lroot / rel) if lroot else None
        if p and p.exists():
            logic_records[oid] = json.loads(p.read_text(encoding="utf-8"))

    return {"inventory": inv, "parser": parser, "data": data, "logic": logic,
            "rules": rules, "diagrams": diagrams, "brd_index": brd,
            "parser_records": parser_records, "logic_records": logic_records}


